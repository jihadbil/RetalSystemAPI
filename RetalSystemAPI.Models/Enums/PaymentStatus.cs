namespace RetalSystemAPI.Models.Enums;

/// <summary>
/// يمثل حالات معالجة وسداد المعاملات المالية والدفعات.
/// </summary>
// تعريف تعداد حالات تسوية الدفعات المالية
public enum PaymentStatus
{
    /// <summary>
    /// الدفعة قيد المعالجة أو بانتظار التأكيد البنكي.
    /// </summary>
    // حالة الدفعة المعلقة
    Pending = 0,

    /// <summary>
    /// تم السداد واكتمال المعاملة المالية بنجاح.
    /// </summary>
    // حالة الدفعة المكتملة
    Completed = 1,

    /// <summary>
    /// فشلت عملية السداد أو تم رفض المعاملة.
    /// </summary>
    // حالة الدفعة الفاشلة
    Failed = 2,

    /// <summary>
    /// تم استرداد وإرجاع كامل المبلغ للعميل.
    /// </summary>
    // حالة الدفعة المستردة بالكامل
    Refunded = 3,

    /// <summary>
    /// تم استرداد وإرجاع جزء من المبلغ للعميل.
    /// </summary>
    // حالة الدفعة المستردة جزئياً
    PartiallyRefunded = 4
}
