namespace RetalSystemAPI.Models.Enums;

/// <summary>
/// يمثل طرق ووسائل الدفع والسداد المعتمدة في العمليات المالية ونقاط البيع.
/// </summary>
// تعريف تعداد طرق ووسائل الدفع المالي
public enum PaymentMethod
{
    /// <summary>
    /// دفع نقدي (كاش).
    /// </summary>
    // وسيلة الدفع النقدي
    Cash = 1,

    /// <summary>
    /// تحويل مصرفي مباشر إلى الحساب البنكي.
    /// </summary>
    // وسيلة التحويل المصرفي
    BankTransfer = 2,

    /// <summary>
    /// بطاقة مصرفية عبر أجهزة نقاط البيع الإلكترونية (POS / Debit / Credit).
    /// </summary>
    // وسيلة الدفع بالبطاقة المصرفية
    CreditCard = 3,

    /// <summary>
    /// دفع آجل على الحساب الائتماني للعميل.
    /// </summary>
    // وسيلة البيع الآجل على الحساب
    Credit = 4,

    /// <summary>
    /// صك مصرفي / شيك بنكي.
    /// </summary>
    // وسيلة السداد بالصك المصرفي
    Cheque = 5,

    /// <summary>ملخص فاتورة مسددة بأكثر من وسيلة؛ ليس وسيلة قبض مستقلة.</summary>
    Multiple = 6
}
