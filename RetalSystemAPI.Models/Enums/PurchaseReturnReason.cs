namespace RetalSystemAPI.Models.Enums;

/// <summary>
/// يمثل الأسباب النظامية لإرجاع البضاعة المشتراة إلى المورد.
/// </summary>
// تعريف تعداد أسباب مردودات المشتريات
public enum PurchaseReturnReason
{
    /// <summary>
    /// بضاعة معيبة مصنعياً أو متضررة وتالفة أثناء النقل والتخزين.
    /// </summary>
    // سبب بضاعة معيبة أو تالفة
    Defective = 1,

    /// <summary>
    /// بضاعة غير مطابقة للمواصفات أو أمر الشراء المتفق عليه.
    /// </summary>
    // سبب عدم مطابقة المواصفات
    WrongSpecification = 2,

    /// <summary>
    /// أصناف قريبة من تاريخ الانتهاء أو منتهية الصلاحية.
    /// </summary>
    // سبب قرب أو انتهاء الصلاحية
    NearExpiryOrExpired = 3,

    /// <summary>
    /// كميات فائضة عن الطاقة الاستيعابية للمخزون أو بضاعة متفق على إرجاعها مسبقاً.
    /// </summary>
    // سبب الفائض المخزوني أو الاتفاق المسبق
    ExcessStock = 4,

    /// <summary>
    /// سبب إرجاع آخر غير مصنف أعلاه يتم توضيحه في الملاحظات.
    /// </summary>
    // سبب إرجاع آخر
    Other = 5
}
