namespace RetalSystemAPI.Models.Enums;

/// <summary>
/// يمثل دورة حياة وحالات أوامر الشراء الصادرة للموردين.
/// </summary>
// تعريف تعداد حالات أوامر الشراء
public enum PurchaseOrderStatus
{
    /// <summary>
    /// مسودة أمر شراء أولية قيد التحرير والمراجعة.
    /// </summary>
    // حالة مسودة أمر الشراء
    Draft = 1,

    /// <summary>
    /// أمر شراء مؤكد ومُرسل رسمياً إلى المورد.
    /// </summary>
    // حالة أمر الشراء المؤكد
    Confirmed = 2,

    /// <summary>
    /// تم استلام جزء من الأصناف المطلوبة في المستودع.
    /// </summary>
    // حالة الاستلام الجزئي للبضاعة
    PartiallyReceived = 3,

    /// <summary>
    /// تم استلام كامل الكميات المطلوبة وإغلاق أمر الشراء.
    /// </summary>
    // حالة الاستلام الكامل وإغلاق الأمر
    Received = 4,

    /// <summary>
    /// أمر الشراء ملغى ولم يعد سارياً.
    /// </summary>
    // حالة أمر الشراء الملغى
    Cancelled = 5
}
