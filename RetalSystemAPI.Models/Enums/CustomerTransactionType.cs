namespace RetalSystemAPI.Models.Enums;

/// <summary>
/// يحدد نوع حركة حساب العميل في دفتر الأستاذ المالي.
/// </summary>
// تعريف تعداد أنواع حركات حسابات العملاء
public enum CustomerTransactionType
{
    /// <summary>
    /// فاتورة بيع آجلة أو نقدية تمثل دينًا مستحقًا على العميل (مدين).
    /// </summary>
    // حركة فاتورة مبيعات تزيد من مديونية العميل
    SalesInvoice = 1,

    /// <summary>
    /// سداد أو دفعة نقدية/بنكية مقبوضة من العميل تخفض المديونية (دائن).
    /// </summary>
    // حركة سداد وقبض دفعة مالية من العميل
    Payment = 2,

    /// <summary>
    /// مرتجع مبيعات يقلل من الدين المستحق على العميل (دائن).
    /// </summary>
    // حركة مردودات مبيعات وبضاعة مسترجعة
    SalesReturn = 3,

    /// <summary>
    /// رصيد افتتاحي مستحق على العميل مسجل عند تدشين الحساب.
    /// </summary>
    // حركة الرصيد الافتتاحي للعميل
    OpeningBalance = 4,

    /// <summary>
    /// تسوية حساب يدوية لتصحيح أو تعديل رصيد العميل.
    /// </summary>
    // حركة تسوية حساب رصيد العميل
    Adjustment = 5,

    /// <summary>
    /// قيد عكسي لإلغاء أثر مستند مالي ملغى سابقاً.
    /// </summary>
    // حركة قيد عكسي لمستند ملغى
    Reversal = 6
}
