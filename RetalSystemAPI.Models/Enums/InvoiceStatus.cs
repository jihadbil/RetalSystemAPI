namespace RetalSystemAPI.Models.Enums;

/// <summary>
/// يمثل الحالات التشغيلية والمالية لفواتير المبيعات والمشتريات.
/// </summary>
// تعريف تعداد حالات الفاتورة في النظام
public enum InvoiceStatus
{
    /// <summary>
    /// مسودة أولية غير معتمدة وغير مؤثرة على الحسابات أو المخزون.
    /// </summary>
    // حالة الفاتورة كمسودة
    Draft = 0,

    /// <summary>
    /// فاتورة معلقة بانتظار التحصيل أو التأكيد.
    /// </summary>
    // حالة الفاتورة المعلقة
    Pending = 1,

    /// <summary>
    /// فاتورة مدفوعة ومسددة بالكامل.
    /// </summary>
    // حالة الفاتورة المسددة بالكامل
    Paid = 2,

    /// <summary>
    /// فاتورة مسددة جزئياً وما زال هناك رصيد متبقٍ.
    /// </summary>
    // حالة الفاتورة المسددة جزئياً
    PartiallyPaid = 3,

    /// <summary>
    /// فاتورة ملغاة قبل ترحيلها نهائياً.
    /// </summary>
    // حالة الفاتورة الملغاة
    Cancelled = 4,

    /// <summary>
    /// فاتورة مبطلة ومستبعدة محاسبياً.
    /// </summary>
    // حالة الفاتورة المبطلة
    Voided = 5
}
