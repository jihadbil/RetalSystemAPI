namespace RetalSystemAPI.Models.Enums;

/// <summary>
/// يمثل دورة حياة وحالات طلبات وتحويلات البضائع بين المستودعات والفروع.
/// </summary>
// تعريف تعداد حالات تحويل المخزون بين المستودعات
public enum StockTransferStatus
{
    /// <summary>
    /// مسودة تحويل بضاعة قيد الإعداد ولم يتم خصمها أو استلامها.
    /// </summary>
    // حالة مسودة التحويل
    Draft = 1,

    /// <summary>
    /// تحويل مؤكد وتم خصم الكميات من المستودع المصدر وفي طريقها للمستلم.
    /// </summary>
    // حالة التحويل المؤكد
    Confirmed = 2,

    /// <summary>
    /// تم استلام البضاعة في المستودع الهدف وترحيل العملية بالكامل.
    /// </summary>
    // حالة التحويل المكتمل والمرحل
    Completed = 3,

    /// <summary>
    /// تحويل ملغى وتمت استعادة الأرصدة للمستودع المصدر.
    /// </summary>
    // حالة التحويل الملغى
    Cancelled = 4
}
