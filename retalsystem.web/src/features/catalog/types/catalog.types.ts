// أنواع ونماذج كتالوج المنتجات والتصنيفات والوحدات

export interface ProductBarCodeDto {
  id?: string;
  productId?: string;
  barCode: string;
  title?: string;
  description?: string;
  isPrimary?: boolean;
}

export interface ProductUnitDto {
  id?: string;
  productId?: string;
  unitId: string;
  unitName?: string;
  conversionFactor: number;
  salePrice?: number;
  purchasePrice?: number;
  isDefault?: boolean;
}

export interface ProductImageDto {
  id?: string;
  productId?: string;
  imageUrl: string;
  isPrimary: boolean;
  displayOrder?: number;
}

export interface ProductDto {
  id: string;
  name: string;
  code: string;
  description?: string;
  categoryId: string;
  categoryName?: string;
  defaultUnitId?: string;
  defaultUnitName?: string;
  costPrice: number;
  salePrice: number;
  averagePrice?: number;
  minStockLevel?: number;
  isActive: boolean;
  primaryImageUrl?: string;
  currentStock?: number;
  units?: ProductUnitDto[];
  barCodes?: ProductBarCodeDto[];
  images?: ProductImageDto[];
}

export interface CreateProductRequest {
  name: string;
  code: string;
  description?: string;
  categoryId: string;
  defaultUnitId?: string;
  costPrice: number;
  salePrice: number;
  barCodes?: { barCode: string; title?: string; description?: string }[];
  units?: { unitId: string; conversionFactor: number; isDefault?: boolean }[];
  openingBalances?: { warehouseId: string; warehouseType?: number; quantity: number }[];
}

export interface CategoryDto {
  id: string;
  name: string;
  description?: string;
  parentCategoryId?: string | null;
  parentCategoryName?: string | null;
  isActive: boolean;
  sortOrder?: number;
  productsCount?: number;
  productCount?: number;
  subCategories?: CategoryDto[];
}

export interface CreateCategoryRequest {
  name: string;
  description?: string;
  parentCategoryId?: string | null;
  isActive?: boolean;
  sortOrder?: number;
}

export interface UpdateCategoryRequest {
  name: string;
  description?: string;
  parentCategoryId?: string | null;
  isActive?: boolean;
  sortOrder?: number;
}

export interface UnitDto {
  id: string;
  name: string;
  symbol: string;
  isBaseUnit: boolean;
}

export interface ImportPreviewRow {
  rowNumber: number;
  name: string;
  code: string;
  categoryName: string;
  salePrice: number;
  costPrice: number;
  barCode?: string;
  unitName?: string;
  isValid: boolean;
  error?: string;
}

export interface ProductImportResult {
  categoriesImported: number;
  productsImported: number;
  barcodesImported: number;
  autoGeneratedBarcodesCount: number;
  unitsImported: number;
  stocksInitialized: number;
  failedRowsCount: number;
  warnings: string[];
  errors: string[];
  isSuccess: boolean;
}
